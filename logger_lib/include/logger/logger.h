#pragma once
// #pragma once — говорит компилятору: "подключай этот файл только один раз",
// даже если разные .cpp файлы попытаются подключить его несколько раз.
// Это защита от ошибок двойного определения класса.

#include <string>
// Подключаем std::string — он нам нужен для текста сообщений и имени файла.

namespace logger {
// namespace — это "пространство имён". Всё, что внутри, будет называться
// logger::Level, logger::Logger и т.д. Это защищает от конфликтов имён,
// если кто-то ещё в своём коде назовёт класс "Logger".

// Уровни важности сообщений.
// enum class (в отличие от старого enum) — типобезопасный:
// нельзя случайно сравнить Level с обычным int или перепутать с другим enum.
enum class Level {
    Info = 0,      // обычная информация
    Warning = 1,   // предупреждение
    Error = 2      // ошибка
};

// Позволяет сравнивать уровни важности через <, <=, >= и т.д.
inline bool operator<(Level lhs, Level rhs)
{
    return static_cast<int>(lhs) < static_cast<int>(rhs);
}
// Значения 0, 1, 2 нужны, чтобы можно было сравнивать уровни:
// "если уровень сообщения >= уровня по умолчанию — пишем в файл".

class Logger {
public:
    // Конструктор — вызывается один раз при создании объекта Logger.
    // Принимает: имя файла журнала и уровень важности по умолчанию.
    Logger(const std::string& filename, Level defaultLevel);

    // Деструктор — вызывается автоматически, когда объект Logger уничтожается.
    // Здесь мы закроем файл, если он был открыт.
    ~Logger();

    // Записать сообщение в журнал.
    // Если level ниже текущего уровня по умолчанию — сообщение НЕ запишется.
    // Возвращаем bool — успешно ли прошла запись (это вместо исключений,
    // как и требуется в задании: "не использовать исключения для бизнес-логики").
    bool Log(const std::string& message, Level level);

    // Изменить уровень важности по умолчанию после создания объекта.
    void SetDefaultLevel(Level level);

    // Узнать текущий уровень важности по умолчанию.
    Level GetDefaultLevel() const;
    // const в конце — значит, этот метод не изменяет объект,
    // а только "читает" его состояние. Хорошая практика ООП.

private:
    // Здесь мы скрываем детали реализации (сам файл, mutex и т.д.)
    // Используем идиому Pimpl (Pointer to Implementation):
    // в заголовке — только указатель на приватный класс,
    // а сама реализация — в .cpp файле.
    // Зачем: если поменяется внутренняя реализация (например, добавим mutex
    // для потокобезопасности в Части 2), не придётся пересобирать
    // все программы, которые используют библиотеку — заголовок не изменится.
    class Impl;
    Impl* pImpl;

    // Запрещаем копирование объекта Logger.
    // Почему: у нас внутри указатель на Impl (который держит открытый файл).
    // Если бы Logger можно было копировать "по умолчанию" (как структуру),
    // два объекта Logger могли бы одновременно "владеть" одним файлом —
    // это привело бы к ошибкам при закрытии/использовании файла.
    Logger(const Logger&) = delete;
    Logger& operator=(const Logger&) = delete;
};

} // namespace logger